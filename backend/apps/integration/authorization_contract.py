# Domain authority: UserOrganization roles + consumer CanEdit. Global AdminApps
# admin/superadmin deliberately have no implicit product grants. Approval/export
# and administration are not inferred from rank. They await specific domain RBAC.
ROLE_OPERATIONS = {
    'ISO_SMART': {'viewer': ('read',), 'auditor': ('read',),
                  'user': ('read', 'create', 'update'),
                  'iso_manager': ('read', 'create', 'update'),
                  'org_admin': ('read', 'create', 'update', 'delete')},
    'MEDSUPPLIER': {'viewer': ('read',), 'auditor': ('read',),
                    'user': ('read', 'create', 'update'),
                    'iso_manager': ('read',),
                    'org_admin': ('read', 'create', 'update', 'delete')},
}


def valid_scopes(scopes, product):
    return (type(scopes) is list and bool(scopes)
            and all(type(s) is str and s in CATALOG.get(product, ()) for s in scopes)
            and len(set(scopes)) == len(scopes))


def role_scopes(scopes, product, role):
    if not valid_scopes(scopes, product):
        return []
    operations = ROLE_OPERATIONS.get(product, {}).get(role, ())
    return sorted(s for s in scopes if s.rsplit(':', 1)[1] in operations)
